// ─── Chair Sub-Resources (v32.4) ─────────────────────────────────────────────

const ChairDef = require("../../../organization/models/Chair");
const AppointmentDef = require("../../../organization/appointment/models/appointment.model");
const BranchDef = require("../../../shared/models/Branch");
const getModel = require("../../../core/db/getModel");

/**
 * GET /api/v1/branches/:id/chairs
 * Returns active Chair documents for a branch.
 * The frontend uses this to dynamically build the chair selector.
 */
exports.getChairs = asyncHandler(async (req, res) => {
    const Branch = getModel(req.dbConnection, BranchDef);
    const branch = await Branch.findById(req.params.id).lean();

    if (!branch) {
        return res.status(404).json({ success: false, message: "Branch not found" });
    }

    // Subdocument _id is a proper ObjectId (auto-generated by Mongoose).
    // Convert to string so the frontend receives a valid 24-char hex chairId.
    const activeChairs = (branch.chairs || [])
        .filter(c => c.isActive)
        .map(c => ({
            _id:     c._id.toString(),
            name:    c.name,
            isActive: c.isActive,
        }));

    res.json({ success: true, data: activeChairs });
});



/**
 * GET /api/v1/branches/:id/chair-analytics
 * Returns per-chair analytics for a branch: utilization %, revenue, appointment count.
 *
 * Query params:
 *   startDate (ISO) — defaults to 30 days ago
 *   endDate   (ISO) — defaults to now
 */
exports.getChairAnalytics = asyncHandler(async (req, res) => {
    const Appointment = getModel(req.dbConnection, AppointmentDef);
    const Branch      = getModel(req.dbConnection, BranchDef);
    const Chair       = getModel(req.dbConnection, ChairDef);

    const branchId = req.params.id;

    // Resolve date window (default: last 30 days)
    const endDate   = req.query.endDate   ? new Date(req.query.endDate)   : new Date();
    const startDate = req.query.startDate
        ? new Date(req.query.startDate)
        : new Date(endDate.getTime() - 30 * 24 * 60 * 60 * 1000);

    // Validate date range
    if (startDate >= endDate) {
        return res.status(400).json({ success: false, message: "startDate must be before endDate" });
    }

    // Fetch branch for context and embedded chairs
    const branch = await Branch.findById(branchId).lean();
    if (!branch) return res.status(404).json({ success: false, message: "Branch not found" });

    // Filter active chairs embedded in the branch
    const chairs = (branch.chairs || [])
        .filter(c => c.isActive)
        .map(c => ({ ...c, _id: c.id || c._id }))
        .sort((a, b) => a.name.localeCompare(b.name));

    // Analytics aggregation — group completed appointments by chair
    const stats = await Appointment.aggregate([
        {
            $match: {
                branchId: branch._id,
                status: "completed",
                startTime: { $gte: startDate, $lte: endDate },
            },
        },
        {
            $group: {
                _id: "$chairId",
                totalRevenue:      { $sum: "$revenueAmount" },
                totalAppointments: { $sum: 1 },
                totalDuration:     { $sum: "$duration" }, // minutes
            },
        },
    ]);

    // Build lookup map by chairId string
    const statsMap = {};
    for (const s of stats) {
        statsMap[s._id?.toString()] = s;
    }

    // Calculate total available minutes per chair in the date window
    const windowDays = Math.max(1, Math.round((endDate - startDate) / (1000 * 60 * 60 * 24)));
    // Use org working hours (default 9h/day = 540 min)
    const dailyMinutes = 9 * 60;
    const totalAvailableMinutes = windowDays * dailyMinutes;

    // Merge chair list with stats
    const chairAnalytics = chairs.map(chair => {
        const s = statsMap[chair._id.toString()] || {};
        const usedMinutes    = s.totalDuration || 0;
        const utilizationPct = totalAvailableMinutes > 0
            ? Math.round((usedMinutes / totalAvailableMinutes) * 100)
            : 0;

        return {
            chairId:           chair._id,
            chairName:         chair.name,
            totalRevenue:      s.totalRevenue || 0,
            totalAppointments: s.totalAppointments || 0,
            totalDuration:     usedMinutes,
            utilizationPct:    Math.min(100, utilizationPct),
        };
    });

    // Network totals
    const networkRevenue      = chairAnalytics.reduce((sum, c) => sum + c.totalRevenue, 0);
    const networkAppointments = chairAnalytics.reduce((sum, c) => sum + c.totalAppointments, 0);
    const avgUtilization      = chairs.length > 0
        ? Math.round(chairAnalytics.reduce((sum, c) => sum + c.utilizationPct, 0) / chairs.length)
        : 0;
    const revenuePerChair     = chairs.length > 0 ? Math.round(networkRevenue / chairs.length) : 0;

    res.json({
        success: true,
        data: {
            branchId,
            branchName:        branch.name,
            numberOfOperatories: branch.numberOfOperatories,
            windowDays,
            startDate:         startDate.toISOString(),
            endDate:           endDate.toISOString(),
            summary: {
                networkRevenue,
                networkAppointments,
                avgUtilizationPct: avgUtilization,
                revenuePerChair,
            },
            chairs: chairAnalytics,
        },
    });
});
