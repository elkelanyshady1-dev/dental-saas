"use strict";

const asyncHandler = require("@utils/asyncHandler");
const branchesService = require("../services/branches.service");
const { validateCreateBranch, validateUpdateBranch } = require("../validators/branches.validator");

/**
 * POST /api/v1/branches
 */
exports.createBranch = asyncHandler(async (req, res) => {
    const { error } = validateCreateBranch(req.body);
    if (error) {
        return res.status(400).json({
            success: false,
            error: { code: "VALIDATION_ERROR", message: error },
        });
    }

    const branch = await branchesService.createBranch(
        req.body,
        req, // tenant context — replaces organizationId
        req.user._id.toString()
    );

    res.status(201).json({
        success: true,
        data: branch,
        message: "Branch created successfully",
    });
});

/**
 * GET /api/v1/branches
 */
exports.listBranches = asyncHandler(async (req, res) => {
    const result = await branchesService.listBranches(req, { // tenant context — replaces organizationId
        page: req.query.page,
        limit: req.query.limit,
        search: req.query.search,
        isActive: req.query.isActive,
        type: req.query.type,
    });

    res.json({
        success: true,
        data: result.data,
        pagination: result.pagination,
    });
});

